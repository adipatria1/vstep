pub fn get_all_presets() -> HashMap<String, HashMap<String, Vec<Preset>>> {
    let mut result: HashMap<String, HashMap<String, Vec<Preset>>> = HashMap::new();
    
    let mut trend_cats: HashMap<String, Vec<Preset>> = HashMap::new();
    trend_cats.insert("cat_a".to_string(), Vec::new());
    trend_cats.insert("cat_b".to_string(), Vec::new());
    trend_cats.insert("cat_c".to_string(), Vec::new());
    trend_cats.insert("cat_d".to_string(), Vec::new());

    let mut counter_cats: HashMap<String, Vec<Preset>> = HashMap::new();
    counter_cats.insert("cat_a".to_string(), Vec::new());
    counter_cats.insert("cat_b".to_string(), Vec::new());
    counter_cats.insert("cat_c".to_string(), Vec::new());
    counter_cats.insert("cat_d".to_string(), Vec::new());

    for t in get_raw_templates() {
        let mut p_trend = t.clone();
        p_trend.key = format!("TREND | {}", t.sub);
        p_trend.label = p_trend.key.clone();
        p_trend.mode = "One-Way Trend".to_string();
        if let Some(vec) = trend_cats.get_mut(&t.cat) {
            vec.push(p_trend);
        }

        let mut p_counter = t.clone();
        p_counter.key = format!("COUNTER | {}", t.sub);
        p_counter.label = p_counter.key.clone();
        p_counter.mode = "One-Way Counter".to_string();
        if let Some(vec) = counter_cats.get_mut(&t.cat) {
            vec.push(p_counter);
        }
    }

    result.insert("TREND".to_string(), trend_cats);
    result.insert("COUNTER".to_string(), counter_cats);
    result
}

pub fn find_preset(preset_key: &str) -> Option<Preset> {
    let presets = get_all_presets();
    for (_mode, cats) in presets {
        for (_cat, list) in cats {
            for p in list {
                if p.key == preset_key {
                    return Some(p);
                }
            }
        }
    }
    None
}
