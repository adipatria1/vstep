use serde::{Deserialize, Serialize};
use std::collections::HashMap;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Preset {
    pub key: String,
    pub label: String,
    pub mode: String,
    pub cat: String,
    pub sub: String,
    pub tp_type: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tp_val_key: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tp_bar_key: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tp_mult: Option<f64>,
    pub sl_type: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub sl_val_key: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub sl_bar_key: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub sl_mult: Option<f64>,
    pub use_trail: bool,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub trail_type: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub trail_act_mult: Option<f64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub trail_dist_mult: Option<f64>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub trail_act_key: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub trail_dist_key: Option<String>,
}

